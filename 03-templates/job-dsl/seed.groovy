// Seed job DSL: one folder per team (with its own credentials scope + RBAC pattern),
// one multibranch job per repo, plus shared ops jobs. Driven by teams.yaml in the same repo.
//
// teams.yaml:
//   - name: payments
//     repos: [payments-api, ledger]
//   - name: search
//     repos: [search-api]
//
// With Job DSL script security on, the SnakeYAML import needs one-time script approval
// (or keep the team list as a Groovy map in this file).

import org.yaml.snakeyaml.Yaml

def teams = new Yaml().load(readFileFromWorkspace('teams.yaml'))

teams.each { team ->
  folder(team.name) {
    displayName(team.name.capitalize())
    description("Owned by team-${team.name}. Generated by seed job — do not edit in UI.")
  }

  team.repos.each { repo ->
    multibranchPipelineJob("${team.name}/${repo}") {
      displayName(repo)
      branchSources {
        branchSource {
          source {
            github {
              id("${team.name}-${repo}")
              repoOwner('acme')
              repository(repo)
              repositoryUrl("https://github.com/acme/${repo}")
              configuredByUrl(true)
              credentialsId('github-app')
              traits {
                gitHubBranchDiscovery { strategyId(1) }          // exclude branches that are also PRs
                gitHubPullRequestDiscovery { strategyId(1) }     // build merge commit
                gitHubForkDiscovery {
                  strategyId(1)
                  trust { gitHubTrustPermissions() }             // only collaborators' forks are trusted
                }
                gitHubTagDiscovery()
                cloneOption {
                  extension { shallow(true); depth(1); noTags(false); reference(''); timeout(10) }
                }
              }
            }
          }
        }
      }
      factory { workflowBranchProjectFactory { scriptPath('Jenkinsfile') } }
      orphanedItemStrategy {
        discardOldItems { daysToKeep(7); numToKeep(20) }
      }
      triggers { periodicFolderTrigger { interval('1d') } }      // safety net; webhooks do the real work
    }
  }
}

folder('ops') { description('Platform operational jobs') }

pipelineJob('ops/jenkins-backup-check') {
  description('Verifies latest backup snapshot exists and is < 26h old')
  properties { pipelineTriggers { triggers { cron { spec('H 7 * * *') } } } }
  definition {
    cpsScm {
      scm {
        git {
          remote { url('https://github.com/acme/jenkins-config.git'); credentials('github-app') }
          branch('*/main')
        }
      }
      scriptPath('jobs/backup-check/Jenkinsfile')
      lightweight(true)
    }
  }
}

listView('Failing') {
  description('All jobs whose last build failed')
  recurse(true)
  jobFilters { status { status(Status.FAILED) } }
  columns { status(); weather(); name(); lastSuccess(); lastFailure(); lastDuration(); buildButton() }
}
